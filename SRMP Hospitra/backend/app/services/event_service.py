"""Security events: normalisation, validation, persistence and querying.

V1 accepts SYNTHETIC events only. There is no ingestion endpoint: events are created
exclusively by the simulation service from predefined scenarios.
"""

from __future__ import annotations

import ipaddress
import json
from dataclasses import dataclass, field, replace
from datetime import datetime
from typing import Any

from sqlalchemy import and_, exists, or_, select
from sqlalchemy.orm import Session, aliased, joinedload, selectinload

from app.core.constants import EventType, Severity
from app.core.exceptions import DomainValidationError, NotFoundError
from app.core.time import ensure_utc, utcnow
from app.models import Asset, Branch, Detection, NetworkZone, SecurityEvent
from app.schemas.security_event import AssetRef, EventRead, MatchedRuleRef, ZoneBrief
from app.services.common import PageParams, paginate


@dataclass
class EventDraft:
    event_type: EventType | str
    branch_id: str
    message: str
    scenario_id: str
    occurred_at: datetime
    severity: Severity | str = Severity.LOW
    source_asset_id: str | None = None
    destination_asset_id: str | None = None
    source_zone_id: str | None = None
    destination_zone_id: str | None = None
    source_ip: str | None = None
    destination_ip: str | None = None
    metadata: dict[str, Any] = field(default_factory=dict)
    is_simulated: bool = True
    simulation_run_id: str | None = None


def _invalid(field_name: str, message: str) -> DomainValidationError:
    return DomainValidationError("Event validation failed.", [{"field": field_name, "message": message}])


def _valid_ip_or_network(value: str) -> bool:
    try:
        ipaddress.ip_address(value)
        return True
    except ValueError:
        try:
            ipaddress.ip_network(value, strict=False)
            return True
        except ValueError:
            return False


def normalise_draft(db: Session, draft: EventDraft) -> EventDraft:
    """Validate a draft and fill derived context (zone and IP from registered assets)."""
    if draft.is_simulated is not True:
        raise _invalid("is_simulated", "Hospitra only accepts events generated by its scenarios.")
    try:
        event_type = EventType(draft.event_type)
    except ValueError as exc:
        raise _invalid("event_type", f"Unknown event type '{draft.event_type}'.") from exc
    try:
        severity = Severity(draft.severity)
    except ValueError as exc:
        raise _invalid("severity", f"Unknown severity '{draft.severity}'.") from exc
    scenario_id = (draft.scenario_id or "").strip()
    if not scenario_id:
        raise _invalid("scenario_id", "A scenario identifier is required.")
    message = " ".join((draft.message or "").split())
    if not message:
        raise _invalid("message", "A human-readable description is required.")
    if not isinstance(draft.occurred_at, datetime):
        raise _invalid("occurred_at", "An event timestamp is required.")
    if db.get(Branch, draft.branch_id) is None:
        raise _invalid("branch_id", "Unknown branch.")
    if not isinstance(draft.metadata, dict):
        raise _invalid("metadata", "Metadata must be an object.")
    try:
        json.dumps(draft.metadata)
    except (TypeError, ValueError) as exc:
        raise _invalid("metadata", "Metadata must be JSON-serialisable.") from exc

    resolved: dict[str, Any] = {}
    for side in ("source", "destination"):
        asset_id = getattr(draft, f"{side}_asset_id")
        zone_id = getattr(draft, f"{side}_zone_id")
        ip = getattr(draft, f"{side}_ip")
        if asset_id:
            asset = db.get(Asset, asset_id)
            if asset is None:
                raise _invalid(f"{side}_asset_id", "Unknown asset.")
            if zone_id and zone_id != asset.zone_id:
                raise _invalid(f"{side}_zone_id", "Zone does not match the asset's registered zone.")
            zone_id = asset.zone_id
            ip = ip or asset.ip_address
        elif zone_id and db.get(NetworkZone, zone_id) is None:
            raise _invalid(f"{side}_zone_id", "Unknown zone.")
        if ip is not None and not _valid_ip_or_network(str(ip)):
            raise _invalid(f"{side}_ip", "Must be an IP address or CIDR range.")
        resolved[f"{side}_zone_id"] = zone_id
        resolved[f"{side}_ip"] = ip

    return replace(
        draft,
        event_type=event_type,
        severity=severity,
        scenario_id=scenario_id,
        message=message,
        occurred_at=ensure_utc(draft.occurred_at),
        metadata=dict(sorted(draft.metadata.items())),
        **resolved,
    )


def create_event(db: Session, draft: EventDraft, *, created_at: datetime | None = None) -> SecurityEvent:
    """Validate and persist (flush, no commit). The caller owns the transaction."""
    clean = normalise_draft(db, draft)
    event = SecurityEvent(
        event_type=clean.event_type,
        branch_id=clean.branch_id,
        source_asset_id=clean.source_asset_id,
        destination_asset_id=clean.destination_asset_id,
        source_zone_id=clean.source_zone_id,
        destination_zone_id=clean.destination_zone_id,
        source_ip=clean.source_ip,
        destination_ip=clean.destination_ip,
        severity=clean.severity,
        message=clean.message,
        is_simulated=True,
        scenario_id=clean.scenario_id,
        simulation_run_id=clean.simulation_run_id,
        event_metadata=clean.metadata,
        occurred_at=clean.occurred_at,
        created_at=created_at or utcnow(),
    )
    db.add(event)
    db.flush()
    return event


# ---- read models ---------------------------------------------------------------------------

def _asset_ref(asset: Asset | None) -> AssetRef | None:
    if asset is None:
        return None
    return AssetRef(id=asset.id, asset_tag=asset.asset_tag, name=asset.name,
                    asset_type=asset.asset_type.value, criticality=asset.criticality.value)


def _zone_brief(zone: NetworkZone | None) -> ZoneBrief | None:
    if zone is None:
        return None
    return ZoneBrief(id=zone.id, name=zone.name, code=zone.code, zone_type=zone.zone_type.value, vlan_id=zone.vlan_id)


def detection_status(event: SecurityEvent) -> str:
    if not event.detections:
        return "not_evaluated"
    return "detected" if any(d.matched for d in event.detections) else "no_match"


def event_to_read(event: SecurityEvent) -> EventRead:
    return EventRead(
        id=event.id,
        event_type=event.event_type,
        branch_id=event.branch_id,
        branch_code=event.branch.code,
        source_asset=_asset_ref(event.source_asset),
        destination_asset=_asset_ref(event.destination_asset),
        source_zone=_zone_brief(event.source_zone),
        destination_zone=_zone_brief(event.destination_zone),
        source_ip=event.source_ip,
        destination_ip=event.destination_ip,
        severity=event.severity,
        message=event.message,
        is_simulated=event.is_simulated,
        scenario_id=event.scenario_id,
        simulation_run_id=event.simulation_run_id,
        metadata=event.event_metadata or {},
        occurred_at=event.occurred_at,
        created_at=event.created_at,
        detection_status=detection_status(event),
        matched_rules=[
            MatchedRuleRef(detection_id=d.id, rule_id=d.rule_id, rule_name=d.rule_name, severity=d.severity)
            for d in event.detections if d.matched
        ],
    )


EVENT_LOAD = (
    joinedload(SecurityEvent.branch),
    joinedload(SecurityEvent.source_asset),
    joinedload(SecurityEvent.destination_asset),
    joinedload(SecurityEvent.source_zone),
    joinedload(SecurityEvent.destination_zone),
    selectinload(SecurityEvent.detections),
)


def get_event(db: Session, event_id: str) -> SecurityEvent:
    event = db.get(SecurityEvent, event_id, options=list(EVENT_LOAD))
    if event is None:
        raise NotFoundError(f"Event '{event_id}' was not found.")
    return event


def list_events(
    db: Session,
    page: PageParams,
    *,
    search: str | None = None,
    severity: str | None = None,
    event_type: str | None = None,
    branch_id: str | None = None,
    scenario_id: str | None = None,
    asset_id: str | None = None,
    detection_status_filter: str | None = None,
    since: datetime | None = None,
    until: datetime | None = None,
    order: str = "desc",
) -> tuple[list[EventRead], int]:
    src, dst = aliased(Asset), aliased(Asset)
    stmt = (
        select(SecurityEvent)
        .outerjoin(src, SecurityEvent.source_asset_id == src.id)
        .outerjoin(dst, SecurityEvent.destination_asset_id == dst.id)
        .options(*EVENT_LOAD)
    )
    if search:
        term = f"%{search.strip()}%"
        stmt = stmt.where(or_(
            SecurityEvent.message.ilike(term), SecurityEvent.source_ip.ilike(term),
            SecurityEvent.destination_ip.ilike(term), src.asset_tag.ilike(term), dst.asset_tag.ilike(term),
            SecurityEvent.id.ilike(term),
        ))
    if severity:
        stmt = stmt.where(SecurityEvent.severity == severity)
    if event_type:
        stmt = stmt.where(SecurityEvent.event_type == event_type)
    if branch_id:
        stmt = stmt.where(SecurityEvent.branch_id == branch_id)
    if scenario_id:
        stmt = stmt.where(SecurityEvent.scenario_id == scenario_id)
    if asset_id:
        stmt = stmt.where(or_(SecurityEvent.source_asset_id == asset_id, SecurityEvent.destination_asset_id == asset_id))
    if since:
        stmt = stmt.where(SecurityEvent.occurred_at >= since)
    if until:
        stmt = stmt.where(SecurityEvent.occurred_at <= until)
    if detection_status_filter:
        matched = exists().where(and_(Detection.event_id == SecurityEvent.id, Detection.matched.is_(True)))
        any_eval = exists().where(Detection.event_id == SecurityEvent.id)
        if detection_status_filter == "detected":
            stmt = stmt.where(matched)
        elif detection_status_filter == "no_match":
            stmt = stmt.where(any_eval, ~matched)
        elif detection_status_filter == "not_evaluated":
            stmt = stmt.where(~any_eval)
    ordering = SecurityEvent.occurred_at.desc() if order == "desc" else SecurityEvent.occurred_at.asc()
    stmt = stmt.order_by(ordering, SecurityEvent.created_at.desc(), SecurityEvent.id)
    items, total = paginate(db, stmt, page)
    return [event_to_read(e) for e in items], total


def zone_lookup(db: Session, zone_ids: list[str]) -> dict[str, NetworkZone]:
    if not zone_ids:
        return {}
    return {z.id: z for z in db.scalars(select(NetworkZone).where(NetworkZone.id.in_(zone_ids)))}
