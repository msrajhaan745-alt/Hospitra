/* ---------------- Drawer (stack) ---------------- */
const drawerStack = [];
let drawerReturnFocus = null;

function drawerKey(ev) {
  if (ev.key === "Escape" && !document.querySelector(".modal-backdrop")) {
    ev.preventDefault();
    closeDrawer();
  }
}

function renderDrawer() {
  const root = document.getElementById("drawer-root");
  clear(root);
  if (!drawerStack.length) {
    document.removeEventListener("keydown", drawerKey);
    drawerReturnFocus?.focus?.();
    return;
  }
  document.addEventListener("keydown", drawerKey);
  const entry = drawerStack[drawerStack.length - 1];
  const eyebrow = h("div", { class: "eyebrow" }, entry.eyebrow || "");
  const title = h("h2", { id: "drawer-title" }, entry.title || "");
  const meta = h("div", { class: "meta" });
  const body = h("div", { class: "drawer-body" });
  const foot = h("div", { class: "drawer-foot" });
  foot.hidden = true;
  const closeBtn = h("button", { class: "btn btn-ghost btn-icon", type: "button", "aria-label": "Close panel", onclick: closeDrawer }, icon("x"));
  const backBtn = drawerStack.length > 1
    ? h("button", { class: "btn btn-ghost btn-icon", type: "button", "aria-label": "Back to previous panel", onclick: () => { drawerStack.pop(); renderDrawer(); } }, icon("back"))
    : null;
  const panel = h("aside", { class: `drawer${entry.wide ? " wide" : ""}`, role: "dialog", "aria-modal": "true", "aria-labelledby": "drawer-title" },
    h("div", { class: "drawer-head" }, backBtn, h("div", { class: "titles" }, eyebrow, title, meta), closeBtn), body, foot);
  root.append(h("div", { class: "drawer-backdrop", onclick: closeDrawer }), panel);

  const ctx = {
    setTitle: (t) => { title.textContent = t; entry.title = t; },
    setEyebrow: (t) => { eyebrow.textContent = t; },
    setMeta: (...nodes) => { clear(meta).append(...nodes.flat().filter(Boolean)); },
    setFooter: (...nodes) => { const n = nodes.flat().filter(Boolean); clear(foot).append(...n); foot.hidden = !n.length; },
    reload: load,
    close: closeDrawer,
  };
  async function load() {
    clear(body).append(loadingState());
    try {
      const content = await entry.render(ctx);
      clear(body).append(...[content].flat().filter(Boolean));
    } catch (err) {
      clear(body).append(errorState(err, load));
    }
  }
  load();
  closeBtn.focus();
}

/** Open a detail panel. `render(ctx)` returns (a promise of) the body nodes. */
export function openDrawer({ eyebrow, title, wide = false, render, replace = false }) {
  if (!drawerStack.length) drawerReturnFocus = document.activeElement;
  if (replace) drawerStack.length = 0;
  drawerStack.push({ eyebrow, title, wide, render });
  renderDrawer();
}

export function closeDrawer() {
  drawerStack.length = 0;
  renderDrawer();
}

export const drawerIsOpen = () => drawerStack.length > 0;

/* ---------------- Modal ---------------- */
export function openModal({ title, body, actions = [], size = "" }) {
  const root = document.getElementById("modal-root");
  const returnFocus = document.activeElement;
  const footer = h("div", { class: "modal-foot" });
  const close = () => {
    backdrop.remove();
    document.removeEventListener("keydown", onKey, true);
    returnFocus?.focus?.();
  };
  const onKey = (ev) => {
    if (ev.key === "Escape") { ev.stopPropagation(); close(); }
  };
  for (const a of actions) {
    const btn = h("button", { class: `btn ${a.variant || ""}`.trim(), type: a.submit ? "submit" : "button" }, a.icon ? icon(a.icon) : null, a.label);
    btn.addEventListener("click", (ev) => { ev.preventDefault(); a.onClick?.({ close, button: btn }); });
    footer.append(btn);
  }
  const modal = h("div", { class: `modal ${size}`.trim(), role: "dialog", "aria-modal": "true", "aria-labelledby": "modal-title" },
    h("div", { class: "modal-head" }, h("h2", { id: "modal-title" }, title),
      h("button", { class: "btn btn-ghost btn-icon", type: "button", "aria-label": "Close dialog", onclick: close }, icon("x"))),
    h("div", { class: "modal-body" }, body),
    actions.length ? footer : null);
  const backdrop = h("div", { class: "modal-backdrop", onmousedown: (ev) => { if (ev.target === backdrop) close(); } }, modal);
  root.append(backdrop);
  document.addEventListener("keydown", onKey, true);
  const focusTarget = modal.querySelector("[autofocus], .modal-body input, .modal-body select, .modal-body textarea") || footer.lastElementChild;
  focusTarget?.focus();
  return { close, modal };
}

/** Promise-based confirmation. With `requireText`, the user must type it exactly. */
export function confirmDialog({ title, message, confirmLabel = "Confirm", danger = false, requireText = null }) {
  return new Promise((resolve) => {
    const input = requireText ? h("input", { class: "input", type: "text", autocomplete: "off", "aria-label": `Type ${requireText} to confirm` }) : null;
    const body = h("div", { class: "stack" },
      typeof message === "string" ? h("p", {}, message) : message,
      requireText ? h("div", { class: "field" }, h("label", {}, `Type ${requireText} to confirm`), input) : null);
    let settled = false;
    const finish = (value, close) => { if (!settled) { settled = true; resolve(value); } close(); };
    const { modal, close } = openModal({
      title, body, size: "small",
      actions: [
        { label: "Cancel", variant: "btn-ghost", onClick: ({ close: c }) => finish(false, c) },
        { label: confirmLabel, variant: danger ? "btn-danger solid" : "btn-primary", onClick: ({ close: c }) => {
          if (requireText && input.value.trim() !== requireText) { input.setAttribute("aria-invalid", "true"); input.focus(); return; }
          finish(true, c);
        } },
      ],
    });
    // Resolve false if dismissed via Esc / backdrop / close button.
    const observer = new MutationObserver(() => {
      if (!document.body.contains(modal)) { observer.disconnect(); if (!settled) { settled = true; resolve(false); } }
    });
    observer.observe(document.getElementById("modal-root"), { childList: true });
    input?.focus();
  });
}

export async function withBusy(button, fn) {
  button.disabled = true;
  button.classList.add("is-busy");
  try { return await fn(); } finally {
    button.disabled = false;
    button.classList.remove("is-busy");
  }
}
