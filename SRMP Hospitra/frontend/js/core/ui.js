/* ---------------- Toasts ---------------- */
const TOAST_ICONS = { success: "check", error: "alert", warn: "alert", info: "info", sim: "flask" };

export function toast({ type = "info", title, message, action, timeout = 5200 }) {
  const root = document.getElementById("toast-root");
  const el = h("div", { class: `toast toast-${type}`, role: type === "error" ? "alert" : "status" },
    icon(TOAST_ICONS[type] || "info"),
    h("div", { style: { minWidth: 0, flex: 1 } },
      h("div", { class: "t-title" }, title),
      message ? h("div", { class: "t-msg" }, message) : null,
      action ? h("div", { class: "t-action" },
        h("button", { class: "link-btn", type: "button", onclick: () => { action.onClick(); dismiss(); } }, action.label)) : null),
    h("button", { class: "btn btn-ghost btn-sm btn-icon", type: "button", "aria-label": "Dismiss notification", onclick: () => dismiss() }, icon("x")));
  const dismiss = () => el.remove();
  root.append(el);
  while (root.children.length > 4) root.firstElementChild.remove();
  if (timeout) setTimeout(dismiss, timeout);
  return dismiss;
}

export function toastError(err, title = "Request failed") {
  toast({ type: "error", title, message: err?.message || String(err), timeout: 8000 });
}

/* ---------------- States ---------------- */
export function loadingState(text = "Loading…", compact = false) {
  return h("div", { class: `state${compact ? " compact" : ""}`, role: "status" }, h("div", { class: "spinner" }), h("p", {}, text));
}

export function emptyState({ title = "Nothing to show", message, action, iconName = "info", compact = false } = {}) {
  return h("div", { class: `state${compact ? " compact" : ""}` }, icon(iconName), h("h3", {}, title),
    message ? h("p", {}, message) : null, action || null);
}

export function errorState(err, retry, compact = false) {
  return h("div", { class: `state state-error${compact ? " compact" : ""}`, role: "alert" }, icon("alert"),
    h("h3", {}, "Could not load data"),
    h("p", {}, err?.message || "An unexpected error occurred."),
    retry ? h("button", { class: "btn btn-sm", type: "button", onclick: retry }, icon("refresh"), "Retry") : null);
}

/* ---------------- Badges ---------------- */
const SEV_LEVEL = { Low: 1, Moderate: 2, High: 3, Critical: 4 };

export function severityBadge(severity) {
  if (!severity) return h("span", { class: "dim" }, "—");
  const level = SEV_LEVEL[severity] || 0;
  return h("span", { class: `sev sev-${severity}`, title: `Severity: ${severity}` },
    h("span", { class: "sev-bars", "aria-hidden": "true" }, [1, 2, 3, 4].map((i) => h("i", { class: i <= level ? "on" : "" }))),
    severity);
}

